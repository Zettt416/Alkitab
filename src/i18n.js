export function t(lang, key, params = {}) {
  const dict = UI_TEXTS[lang] || UI_TEXTS.id;
  let text = dict[key] || UI_TEXTS.id[key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return text;
}
